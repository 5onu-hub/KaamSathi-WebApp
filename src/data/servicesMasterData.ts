// Helper functions for dynamic resolution
export function getAllServiceGroups(): ServiceGroup[] {
  return SERVICE_GROUPS_DATA.filter(g => g.active);
}

export function getServiceGroup(groupSlug: string): ServiceGroup | undefined {
  const norm = groupSlug.toLowerCase().trim();
  return SERVICE_GROUPS_DATA.find(
    g => g.slug === norm || g.id === norm || g.name.toLowerCase().replace(/[^a-z0-9]/g, "-") === norm
  );
}

export function getServiceBySlug(serviceSlug: string, groupSlug?: string): { service: ServiceItem; group: ServiceGroup } | undefined {
  const normService = serviceSlug.toLowerCase().trim();
  
  if (groupSlug) {
    const group = getServiceGroup(groupSlug);
    if (group) {
      const service = group.services.find(s => s.slug === normService || s.id === normService);
      if (service) return { service, group };
    }
  }

  // Fallback search across all groups
  for (const group of SERVICE_GROUPS_DATA) {
    const service = group.services.find(s => s.slug === normService || s.id === normService);
    if (service) {
      return { service, group };
    }
  }

  return undefined;
}

export function searchAllServices(query: string): Array<{ service: ServiceItem; group: ServiceGroup }> {
  const q = query.toLowerCase().trim();
  if (!q) return [];

  const results: Array<{ service: ServiceItem; group: ServiceGroup }> = [];

  SERVICE_GROUPS_DATA.forEach(group => {
    group.services.forEach(service => {
      if (
        service.name.toLowerCase().includes(q) ||
        service.description.toLowerCase().includes(q) ||
        service.keywords.some(k => k.toLowerCase().includes(q)) ||
        group.name.toLowerCase().includes(q)
      ) {
        results.push({ service, group });
      }
    });
  });

  return results;
}
